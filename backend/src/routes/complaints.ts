/*
 * Edit complaint.
 */
router.put('/:id', (req, res) => {
  const id = Number(
    req.params.id,
  );

  const complaint =
    getComplaint(id);

  if (!complaint) {
    return fail(
      res,
      404,
      'Complaint not found',
    );
  }

  if (
    req.user!.role === 'student' &&
    complaint.user_id !==
      req.user!.user_id
  ) {
    return fail(
      res,
      403,
      'Forbidden',
    );
  }

  const parsed =
    complaintUpdateSchema.safeParse(
      req.body,
    );

  if (!parsed.success) {
    return fail(
      res,
      400,
      'Invalid complaint payload',
    );
  }

  const data = parsed.data;

  let categoryId =
    complaint.category_id;

  if (data.category !== undefined) {
    const category = db
      .prepare(
        `SELECT category_id
         FROM categories
         WHERE category_name = ?
           AND is_active = 1`,
      )
      .get(data.category) as
      | { category_id: number }
      | undefined;

    if (!category) {
      return fail(
        res,
        400,
        'Invalid category',
      );
    }

    categoryId =
      category.category_id;
  }

  const title =
    data.title ??
    complaint.title;

  const description =
    data.description ??
    complaint.description;

  const location =
    data.location ??
    complaint.location;

  const newPriority =
    data.description !== undefined ||
    data.category !== undefined
      ? priority(
          description,
          data.category ??
            complaint.category,
        )
      : complaint.priority;

  db.prepare(
    `UPDATE complaints
     SET
       title = ?,
       description = ?,
       category_id = ?,
       location = ?,
       priority = ?
     WHERE complaint_id = ?`,
  ).run(
    title,
    description,
    categoryId,
    location,
    newPriority,
    id,
  );

  audit(
    req.user!.user_id,
    'UPDATE',
    'complaints',
    id,
  );

  return ok(
    res,
    shape(getComplaint(id)),
  );
});

