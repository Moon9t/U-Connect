/*
 * SDD complaint query.
 *
 * Database relationships:
 *
 * complaints.user_id       -> users.user_id
 * complaints.category_id   -> categories.category_id
 * complaints.department_id -> departments.department_id
 * users.role_id            -> roles.role_id
 */
const select = `
  SELECT
    c.complaint_id AS id,
    c.complaint_id,
    c.reference_number,
    c.title,
    c.description,
    cat.category_name AS category,
    c.category_id,
    c.location,
    c.priority,
    c.status,
    c.user_id,
    u.username AS user_username,
    u.email AS user_email,
    r.role_name AS user_role,
    d.department_id,
    d.department_name,
    c.submitted_at,
    (
      SELECT cu.updated_at
      FROM complaint_updates cu
      WHERE cu.complaint_id = c.complaint_id
      ORDER BY cu.updated_at DESC
      LIMIT 1
    ) AS last_updated_at
  FROM complaints c
  JOIN users u
    ON u.user_id = c.user_id
  JOIN roles r
    ON r.role_id = u.role_id
  LEFT JOIN categories cat
    ON cat.category_id = c.category_id
  LEFT JOIN departments d
    ON d.department_id = c.department_id
`;

export function shape(r: any) {
  return {
    id: Number(r.id ?? r.complaint_id),
    complaint_id: Number(
      r.complaint_id ?? r.id,
    ),
    reference_number: r.reference_number,
    title: r.title,
    description: r.description,
    category: r.category,
    category_id:
      r.category_id == null
        ? null
        : Number(r.category_id),
    location: r.location,
    priority: r.priority,
    status: r.status,
    user_id: Number(r.user_id),

    user: {
      id: Number(r.user_id),
      username: r.user_username,
      email: r.user_email,
      role: r.user_role,
    },

    department:
      r.department_id == null
        ? null
        : {
            id: Number(r.department_id),
            name: r.department_name,
          },

    submitted_at: r.submitted_at,
    created_at: r.submitted_at,
    updated_at:
      r.last_updated_at ?? r.submitted_at,
  };
}

function getComplaint(id: number) {
  return db
    .prepare(
      `${select}
       WHERE c.complaint_id = ?`,
    )
    .get(id) as any;
}

function allowed(req: any, complaint: any) {
  return (
    req.user.role !== 'student' ||
    complaint.user_id === req.user.user_id
  );
}

function priority(
  description: string,
  category: string,
) {
  const d = description.toLowerCase();

  if (
    [
      'emergency',
      'urgent',
      'critical',
      'immediate',
      'danger',
    ].some((keyword) => d.includes(keyword))
  ) {
    return 'critical';
  }

  if (
    category === 'Exam Hall' ||
    category === 'Safety'
  ) {
    return 'high';
  }

  return 'medium';
}

/*
 * Create complaint.
 */
router.post('/', (req, res) => {
  const parsed = complaintSchema.safeParse(
    req.body,
  );

  if (!parsed.success) {
    return fail(
      res,
      400,
      'Invalid complaint payload',
    );
  }

  const p = parsed.data;

  const category = db
    .prepare(
      `SELECT category_id
       FROM categories
       WHERE category_name = ?
         AND is_active = 1`,
    )
    .get(p.category) as
    | { category_id: number }
    | undefined;

  if (!category) {
    return fail(res, 400, 'Invalid category');
  }

  const department = db
    .prepare(
      `SELECT department_id
       FROM departments
       WHERE department_id = ?
         AND is_active = 1`,
    )
    .get(
      Number(req.body.department_id),
    ) as
    | { department_id: number }
    | undefined;

  if (!department) {
    return fail(
      res,
      400,
      'Department not found',
    );
  }

  const t = nowIso();

  try {
    db.exec('BEGIN');

    /*
     * Temporary reference number is used because the
     * complaint_id is generated by SQLite.
     */
    const result = db
      .prepare(
        `INSERT INTO complaints
         (
           reference_number,
           user_id,
           category_id,
           department_id,
           title,
           description,
           location,
           priority,
           status,
           submitted_at
         )
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      )
      .run(
        'TEMP',
        req.user!.user_id,
        category.category_id,
        department.department_id,
        p.title,
        p.description,
        p.location,
        priority(
          p.description,
          p.category,
        ),
        'pending',
        t,
      );

    const complaintId = Number(
      result.lastInsertRowid,
    );

    const referenceNumber =
      `UC-${complaintId
        .toString()
        .padStart(6, '0')}`;

    db.prepare(
      `UPDATE complaints
       SET reference_number = ?
       WHERE complaint_id = ?`,
    ).run(
      referenceNumber,
      complaintId,
    );

    db.prepare(
      `INSERT INTO complaint_updates
       (
         complaint_id,
         updated_by,
         status,
         comment,
         updated_at
       )
       VALUES (?, ?, ?, ?, ?)`,
    ).run(
      complaintId,
      req.user!.user_id,
      'pending',
      'Complaint submitted',
      t,
    );

    /*
     * Notifications are retained from the existing
     * application because the notification feature is
     * already implemented. This will be audited separately
     * against the migrated user/complaint keys.
     */
    db.prepare(
      `INSERT INTO notifications
       (
         user_id,
         type,
         title,
         description,
         related_complaint_id,
         created_at,
         updated_at
       )
       VALUES (?, ?, ?, ?, ?, ?, ?)`,
    ).run(
      req.user!.user_id,
      'complaint',
      'Complaint submitted',
      `Your complaint "${p.title}" was submitted successfully.`,
      complaintId,
      t,
      t,
    );

    audit(
      req.user!.user_id,
      'CREATE',
      'complaints',
      complaintId,
    );

    db.exec('COMMIT');

    const complaint =
      getComplaint(complaintId);

    return ok(
      res,
      shape(complaint),
      'Complaint submitted',
    );
  } catch {
    try {
      db.exec('ROLLBACK');
    } catch {
      // Ignore rollback errors.
    }

    return fail(
      res,
      500,
      'Failed to submit complaint',
    );
  }
});

/*
 * List complaints.
 */
router.get('/', (req, res) => {
  const q = req.query;

  const page = Math.max(
    1,
    Number(q.page) || 1,
  );

  const pageSize = Math.min(
    100,
    Math.max(
      1,
      Number(q.page_size) || 20,
    ),
  );

  const conditions: string[] = [];
  const args: (string | number)[] = [];

  if (req.user!.role === 'student') {
    conditions.push(
      'c.user_id = ?',
    );
    args.push(req.user!.user_id);
  }

  if (q.reference_number) {
    conditions.push(
      'c.reference_number = ?',
    );
    args.push(
      String(q.reference_number),
    );
  }

  if (q.status) {
    conditions.push('c.status = ?');
    args.push(String(q.status));
  }

  if (q.category) {
    conditions.push(
      'cat.category_name = ?',
    );
    args.push(String(q.category));
  }

  if (q.priority) {
    conditions.push(
      'c.priority = ?',
    );
    args.push(String(q.priority));
  }

  if (q.department_id) {
    conditions.push(
      'c.department_id = ?',
    );
    args.push(
      Number(q.department_id),
    );
  }

  const where =
    conditions.length > 0
      ? ` WHERE ${conditions.join(
          ' AND ',
        )}`
      : '';

  const totalResult = db
    .prepare(
      `SELECT COUNT(*) AS count
       FROM complaints c
       LEFT JOIN categories cat
         ON cat.category_id = c.category_id
       ${where}`,
    )
    .get(...args) as {
    count: number;
  };

  const total = Number(
    totalResult.count,
  );

  const rows = db
    .prepare(
      `${select}
       ${where}
       ORDER BY c.submitted_at DESC
       LIMIT ?
       OFFSET ?`,
    )
    .all(
      ...args,
      pageSize,
      (page - 1) * pageSize,
    ) as any[];

  return res.json({
    data: rows.map(shape),
    total,
    page,
    page_size: pageSize,
    total_pages: Math.max(
      1,
      Math.ceil(
        total / pageSize,
      ),
    ),
  });
});

