/*
 * Update complaint status.
 */
router.put(
  '/:id/status',
  requireRole('admin', 'staff'),
  (req, res) => {
    const id = Number(
      req.params.id,
    );

    const parsed =
      statusSchema.safeParse(
        req.body,
      );

    if (!parsed.success) {
      return fail(
        res,
        400,
        'Invalid status',
      );
    }

    const complaint =
      getComplaint(id);

    if (!complaint) {
      return fail(
        res,
        404,
        'Complaint not found',
      );
    }

    const transitions: Record<
      string,
      string[]
    > = {
      pending: [
        'in-progress',
        'resolved',
        'closed',
      ],
      'in-progress': [
        'resolved',
        'closed',
        'pending',
      ],
      resolved: ['closed'],
      closed: [],
    };

    if (
      !transitions[
        complaint.status
      ]?.includes(
        parsed.data.status,
      )
    ) {
      return fail(
        res,
        400,
        `Cannot transition from '${complaint.status}' to '${parsed.data.status}'`,
      );
    }

    const t = nowIso();

    db.prepare(
      `UPDATE complaints
       SET status = ?
       WHERE complaint_id = ?`,
    ).run(
      parsed.data.status,
      id,
    );

    db.prepare(
      `INSERT INTO complaint_updates
       (
         complaint_id,
         updated_by,
         status,
         comment,
         updated_at
       )
       VALUES (?, ?, ?, ?, ?)`,
    ).run(
      id,
      req.user!.user_id,
      parsed.data.status,
      `Status changed to ${parsed.data.status}`,
      t,
    );

    audit(
      req.user!.user_id,
      'UPDATE_STATUS',
      'complaints',
      id,
    );

    return ok(
      res,
      shape(getComplaint(id)),
    );
  },
);

